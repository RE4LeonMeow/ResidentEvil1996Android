#!/usr/bin/env python3
"""Reproduce the bundled FSRCNN weights; no TensorFlow installation needed.

Converts the unmodified, Apache-2.0 pretrained TensorFlow graph from
Saafke/FSRCNN_Tensorflow to C++ float constants. No game data is used.
"""
import hashlib
import pathlib
import struct
import urllib.request

REVISION='6a4812c4ef1c4f5947d79beafa32a05a6eb4a94d'
URL=f'https://raw.githubusercontent.com/Saafke/FSRCNN_Tensorflow/{REVISION}/models/FSRCNN_x4.pb'

def fields(data):
    at=0
    def varint():
        nonlocal at
        value=shift=0
        while True:
            byte=data[at];at+=1;value|=(byte&127)<<shift;shift+=7
            if byte<128:return value
    while at<len(data):
        tag=varint();wire=tag&7
        if wire==0:value=varint()
        elif wire in (1,2,5):
            size=varint() if wire==2 else 8 if wire==1 else 4
            value=data[at:at+size];at+=size
        else:raise ValueError('Unsupported protobuf wire type')
        yield tag>>3,value

def tensors(data):
    result={}
    for field,node in fields(data):
        if field!=1:continue
        node=list(fields(node));name=dict(node)[1].decode()
        if dict(node)[2]!=b'Const':continue
        for field,attr in node:
            if field!=5:continue
            attr=dict(fields(attr))
            if attr[1]!=b'value':continue
            tensor=dict(fields(dict(fields(attr[2]))[8]))
            if tensor[1]!=1:continue # float32 only
            raw=tensor.get(4,tensor.get(5))
            result[name]=struct.unpack('<'+'f'*(len(raw)//4),raw)
    return result

def main():
    data=urllib.request.urlopen(URL).read()
    digest=hashlib.sha256(data).hexdigest()
    expected=pathlib.Path(__file__).with_name('fsrcnn.sha256').read_text().strip()
    if digest!=expected:raise SystemExit('Pretrained graph checksum mismatch')
    values=tensors(data)
    lines=['// Generated by tools/hd/import_fsrcnn.py; pretrained FSRCNN x4.',
           '// Weights: Saafke/FSRCNN_Tensorflow, Apache-2.0. See licenses/FSRCNN.txt.',
           f'// Upstream graph SHA-256: {digest}', '#pragma once', 'namespace FSRCNNWeights {']
    for i in range(1,9):
        for name in [f'f{i}',f'b{i}']+([f'alpha{i}'] if i<8 else []):
            floats=values[name];lines.append(f'inline constexpr float {name}[]={{')
            for start in range(0,len(floats),8):
                lines.append(','.join(float(v).hex()+'f' for v in floats[start:start+8])+',')
            lines.append('};')
    lines.append('}')
    target=pathlib.Path(__file__).resolve().parents[2]/'src/platform/web/fsrcnn_weights.h'
    target.write_text('\n'.join(lines)+'\n')
    print(target,digest)

if __name__=='__main__':main()
